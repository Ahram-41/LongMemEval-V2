#!/usr/bin/env python3
"""Judge a STALE arm (RUNS/<arm>/gen.jsonl) through an OpenAI-compatible endpoint.

  state4   : mem-test v2 judge (stale_judge_v2.py, verbatim prompt): per answer, one sentence of rationale then
             LABEL in {NEW, OLD, MIXED, NONE}; pass == NEW. max_tokens 160, temperature 0.
  official : STALE/Evaluation/full_eval_performance.py (verbatim system + user prompt): the three probe answers of
             one scenario under one condition are judged together, JSON {dimX_eval: {reasoning, pass}}, temperature 0,
             response_format json_object; parse failure -> all three fail (official behaviour), counted and reported.
             NOTE: mem-test/stale_judge_v2_official.py did NOT use this prompt (it used a per-answer 4-way prompt).

Endpoint: JUDGE_BASE_URL / JUDGE_MODEL / JUDGE_API_KEY (default: the local reader, READER_BASE_URL + READER_MODEL,
thinking off). Scores from different judges are not comparable; compare arms only under the same judge.
Writes RUNS/<arm>/judge_<mode>_<slug>.jsonl (cache), scores_<mode>_<slug>.jsonl, table_<mode>_<slug>.txt.
--ref ARM adds exact McNemar (C0 and every condition) of this arm vs ARM under the same judge.
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import json
import os
import re
import sys
import threading
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from e1.common.stats import mcnemar_exact  # noqa: E402
from e1.stale.common import DIMS, RUNS, client, iter_jsonl  # noqa: E402

RULES = {
    "dim1_query": "The query asks whether an earlier state still holds. NEW = the response says the state has changed and states the updated state. OLD = it affirms the old state. MIXED = it hedges, says both hold, or calls the change an aspiration rather than a fact. NONE = it abstains or says there is no evidence.",
    "dim2_query": "The query falsely presupposes the OLD state. NEW = the response corrects or pushes back on that stale premise using the updated state (it may still help afterwards). OLD = it complies with the premise and builds its answer on the old state, however helpful. MIXED = it complies but also mentions the updated state without correcting the premise. NONE = generic content that fits neither state.",
    "dim3_query": "The query asks for an open-ended recommendation or plan without mentioning the change. NEW = the plan is clearly built on the UPDATED state. OLD = it is built on the old state. MIXED = it draws on both states. NONE = generic advice that does not use the user's situation at all.",
}
SYS4 = ("You are a strict grader of memory-aware assistants. Decide which state of the user the assistant's response is built on. "
        "Write ONE sentence of rationale, then a final line exactly of the form 'LABEL: NEW' or 'LABEL: OLD' or 'LABEL: MIXED' or 'LABEL: NONE'.")

# STALE/Evaluation/judge_prompts.py SYSTEM_PROMPT_ALL_IN_ONE_JUDGE (verbatim)
SYS_OFFICIAL = """
You are a strict and impartial expert evaluator for an AI Assistant Benchmark focusing on Long-Term Memory and Implicit Reasoning.

You will be provided with the Ground Truth Context of a user's state.
Then, you will evaluate THREE distinct responses generated by a Target AI Model to THREE different probing questions (Dimension 1, 2, and 3).

[Ground Truth Context]:
- M_old: The user's outdated state.
- M_new: The user's updated state.
- Hidden Logic: How M_new invalidates M_old.

You must grade each response strictly based on whether it correctly deduces and respects the hidden updated state.

### Scoring Rubrics (Boolean: true for Pass, false for Fail)

* **Dimension 1 (Explicit Probing):** Score `true` ONLY IF Response 1 awares that the information in M_old is possibly NO LONGER VALID. Score `false` if it assumes M_old is still true or claims ignorance.

* **Dimension 2 (Adversarial Robustness):**
  Question 2 contains a FALSE PREMISE based on M_old. Score `true` ONLY IF Response 2 detects the trap, or acknowledges the new state in M_new. Score `false` if it blindly agrees with the false premise.

* **Dimension 3 (Implicit Task):**
  Score `true` ONLY IF the final action, plan, or recommendation in Response 3 is safely adheres to the NEW state established by M_new.
  Score `false` if the action complies with the outdated M_old constraints, OR if the response is too generic, vague.

Evaluate strictly based on the underlying logic, not surface-level word matching.

### Output Format (JSON)
{
  "dim1_eval": {
    "reasoning": "Brief step-by-step reasoning against the Dim 1 rubric.",
    "pass": true/false
  },
  "dim2_eval": {
    "reasoning": "Brief step-by-step reasoning against the Dim 2 rubric.",
    "pass": true/false
  },
  "dim3_eval": {
    "reasoning": "Brief step-by-step reasoning against the Dim 3 rubric.",
    "pass": true/false
  }
}
"""


def official_user(rec, ans):  # full_eval_performance.py judge user prompt (verbatim)
    q = {d: rec["probes"][d]["query"] for d in DIMS}
    return f"""
[Ground Truth Context]
- M_old: "{rec['M_old']}"
- M_new: "{rec['M_new']}"
- Hidden Logic: {rec['explanation']}

--------------------------------------------------
[Dimension 1: Explicit Probing]
Question 1: {q['dim1_query']}
Target Model Response 1: {ans['dim1_query']}

--------------------------------------------------
[Dimension 2: Adversarial Robustness]
Question 2: {q['dim2_query']}
Target Model Response 2: {ans['dim2_query']}

--------------------------------------------------
[Dimension 3: Implicit Task]
Question 3: {q['dim3_query']}
Target Model Response 3: {ans['dim3_query']}
"""


def state4_user(rec, dim, ans):
    return (f"Earlier user statement (OLD state): {rec['M_old']}\nLater user statement (implies a change): {rec['M_new']}\n"
            f"Ground-truth state change: {rec['explanation']}\n\nLabel definitions for this query type: {RULES[dim]}\n\n"
            f"User query: {rec['probes'][dim]['query']}\n\nAssistant response:\n{ans}\n\nRationale and label:")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arm", required=True)
    ap.add_argument("--mode", default="state4", choices=["state4", "official"])
    ap.add_argument("--ref", default="", help="reference arm for paired McNemar (same judge)")
    ap.add_argument("--workers", type=int, default=32)
    a = ap.parse_args()
    base = os.environ.get("JUDGE_BASE_URL") or os.environ["READER_BASE_URL"]
    model = os.environ.get("JUDGE_MODEL") or os.environ.get("READER_MODEL", "Qwen/Qwen3.5-9B")
    local = "localhost" in base
    cl = client(base, os.environ.get("JUDGE_API_KEY", "EMPTY"))
    slug = re.sub(r"[^A-Za-z0-9.]+", "-", model.split("/")[-1])
    dst = RUNS / a.arm
    recs = list(iter_jsonl(dst / "gen.jsonl"))
    conds = list(recs[0]["probes"]["dim1_query"]["answers"])

    cache_p = dst / f"judge_{a.mode}_{slug}.jsonl"
    cache = {r["key"]: r for r in iter_jsonl(cache_p)} if cache_p.exists() else {}
    lock = threading.Lock()
    fc = open(cache_p, "a")
    extra = {"chat_template_kwargs": {"enable_thinking": False}} if local else {}

    jobs = {}  # key -> (messages, kind)
    want = []  # (uid, dim, cond, key)
    for rec in recs:
        for c in conds:
            ans = {d: rec["probes"][d]["answers"][c] for d in DIMS}
            if a.mode == "official":
                msgs = [{"role": "system", "content": SYS_OFFICIAL}, {"role": "user", "content": official_user(rec, ans)}]
                k = hashlib.md5(json.dumps([model, msgs]).encode()).hexdigest()
                jobs[k] = msgs
                want += [(rec["uid"], d, c, k) for d in DIMS]
            else:
                for d in DIMS:
                    msgs = [{"role": "system", "content": SYS4}, {"role": "user", "content": state4_user(rec, d, ans[d])}]
                    k = hashlib.md5(json.dumps([model, msgs]).encode()).hexdigest()
                    jobs[k] = msgs
                    want.append((rec["uid"], d, c, k))
    todo = [(k, m) for k, m in jobs.items() if k not in cache]
    print(f"[stale judge] {a.arm} {a.mode} judge={model}: {len(jobs)} calls, {len(todo)} to make", flush=True)

    def call(item):
        k, msgs = item
        kw = {"response_format": {"type": "json_object"}} if a.mode == "official" else {"max_tokens": 160}
        try:
            r = cl.chat.completions.create(model=model, messages=msgs, temperature=0, extra_body=extra or None, **kw)
            raw = r.choices[0].message.content or ""
        except Exception as e:  # noqa: BLE001
            raw = f"ERROR: {e}"
        row = {"key": k, "raw": raw}
        with lock:
            cache[k] = row
            fc.write(json.dumps(row) + "\n")
            fc.flush()
    with ThreadPoolExecutor(a.workers) as ex:
        list(ex.map(call, todo))

    def parse(raw, dim):
        if a.mode == "official":
            m = re.search(r"```(?:json)?\s*(.*?)\s*```", raw, re.S)
            try:
                res = json.loads(m.group(1) if m else raw)
                return ("PASS" if bool(res.get(f"{dim.split('_')[0]}_eval", {}).get("pass", False)) else "FAIL"), True
            except Exception:  # noqa: BLE001
                return "FAIL", False
        labs = re.findall(r"LABEL:\s*(NEW|OLD|MIXED|NONE)", raw.upper())
        return (labs[-1] if labs else "PARSE"), bool(labs)

    scores, bad = [], 0
    for uid, d, c, k in want:
        lab, ok = parse(cache[k]["raw"], d)
        bad += not ok
        scores.append({"uid": uid, "dim": d.split("_")[0], "cond": c, "label": lab, "pass": int(lab in ("NEW", "PASS"))})
    with open(dst / f"scores_{a.mode}_{slug}.jsonl", "w") as f:
        for s in scores:
            f.write(json.dumps(s) + "\n")

    n = len(recs)
    lines = [f"STALE arm {a.arm}: {n} scenarios, judge {a.mode} / {model}; parse failures {bad} (counted as fail)",
             "pass counts (out of n scenarios):", "dim   " + "".join(f"{c:>14}" for c in conds)]
    S = {(s["uid"], s["dim"], s["cond"]): s for s in scores}
    for d in ("dim1", "dim2", "dim3"):
        lines.append(f"{d}  " + "".join(f"{sum(S[(r['uid'], d, c)]['pass'] for r in recs):>14}" for c in conds))
    if a.mode == "state4":
        for c in ("C0", "O_new_only"):
            if c in conds:
                for d in ("dim1", "dim2", "dim3"):
                    lines.append(f"  {c} {d} labels: {dict(collections.Counter(S[(r['uid'], d, c)]['label'] for r in recs))}")
    pres = {(r["uid"], d.split("_")[0]): r["probes"][d]["n_new_sess"] > 0 for r in recs for d in DIMS}
    lines.append(f"probes with a new-session turn in top-{10}: " + " ".join(
        f"{d}={sum(pres[(r['uid'], d)] for r in recs)}" for d in ("dim1", "dim2", "dim3")))
    if a.ref:
        rp = RUNS / a.ref / f"scores_{a.mode}_{slug}.jsonl"
        R = {(s["uid"], s["dim"], s["cond"]): s for s in iter_jsonl(rp)}
        lines.append(f"paired vs {a.ref} (b = ref pass & arm fail, c = ref fail & arm pass, exact McNemar):")
        for d in ("dim1", "dim2", "dim3"):
            for c in conds:
                ks = [(r["uid"], d, c) for r in recs if (r["uid"], d, c) in R]
                b = sum(R[k]["pass"] and not S[k]["pass"] for k in ks)
                cc = sum((not R[k]["pass"]) and S[k]["pass"] for k in ks)
                lines.append(f"  {d} {c:>13}: ref {sum(R[k]['pass'] for k in ks)} arm {sum(S[k]['pass'] for k in ks)} "
                             f"of {len(ks)}  b={b} c={cc} p={mcnemar_exact(b, cc):.3f}")
    txt = "\n".join(lines)
    (dst / f"table_{a.mode}_{slug}.txt").write_text(txt + "\n")
    print(txt, flush=True)


if __name__ == "__main__":
    main()
